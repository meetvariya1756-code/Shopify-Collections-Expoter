import * as XLSX from 'xlsx';

// Column definitions for the Excel schema
const COLUMNS = [
  { key: 'title',           header: 'Title',            width: 28 },
  { key: 'handle',          header: 'Handle',           width: 28 },
  { key: 'type',            header: 'Type',             width: 10 },
  { key: 'description_html',header: 'Description_HTML', width: 40 },
  { key: 'sort_order',      header: 'Sort_Order',       width: 16 },
  { key: 'rules_json',      header: 'Rules_JSON',       width: 52 },
  { key: 'disjunctive',     header: 'Disjunctive',      width: 12 },
  { key: 'product_tags',    header: 'Product_Tags',     width: 40 },
  { key: 'product_handles', header: 'Product_Handles',  width: 40 },
  { key: 'image_url',       header: 'Image_URL',        width: 48 },
  { key: 'image_alt',       header: 'Image_Alt',        width: 24 },
];

/**
 * Map a collection object -> flat Excel row
 */
function collectionToRow(col) {
  return {
    title: col.title || '',
    handle: col.handle || '',
    type: col.collection_type === 'custom' ? 'custom' : 'smart',
    description_html: col.body_html || '',
    sort_order: col.sort_order || 'best-selling',
    rules_json: col.rules?.length ? JSON.stringify(col.rules) : '',
    disjunctive: col.disjunctive ? 'ANY' : 'ALL',
    product_tags: Array.isArray(col.product_tags) ? col.product_tags.join('; ') : '',
    product_handles: Array.isArray(col.sample_products)
      ? col.sample_products.map(p => p.handle).filter(Boolean).join('; ')
      : '',
    image_url: col.image?.src || '',
    image_alt: col.image?.alt || '',
  };
}

/**
 * Apply styles to header row cells
 */
function styleHeaderRow(ws, numCols) {
  for (let c = 0; c < numCols; c++) {
    const cellRef = XLSX.utils.encode_cell({ r: 0, c });
    if (!ws[cellRef]) continue;
    ws[cellRef].s = {
      fill: { fgColor: { rgb: '4F46E5' } },         // Indigo background
      font: { bold: true, color: { rgb: 'FFFFFF' }, sz: 11 },
      alignment: { horizontal: 'center', vertical: 'center', wrapText: false },
      border: {
        bottom: { style: 'medium', color: { rgb: '312E81' } }
      }
    };
  }
}

/**
 * Apply alternating row fill to data rows
 */
function styleDataRows(ws, numRows, numCols) {
  for (let r = 1; r <= numRows; r++) {
    for (let c = 0; c < numCols; c++) {
      const cellRef = XLSX.utils.encode_cell({ r, c });
      if (!ws[cellRef]) continue;
      ws[cellRef].s = {
        fill: { fgColor: { rgb: r % 2 === 0 ? 'F8F7FF' : 'FFFFFF' } },
        alignment: { vertical: 'center', wrapText: false },
        font: { sz: 10 }
      };
    }
  }
}

/**
 * Generate a styled Excel workbook (.xlsx) from a list of collections.
 * Returns a Buffer.
 */
export function generateExcelWorkbook(collections, storeInfo = {}) {
  const rows = collections.map(collectionToRow);

  // Build worksheet from array of objects
  const ws = XLSX.utils.json_to_sheet(rows, {
    header: COLUMNS.map(c => c.key)
  });

  // Override header display names (row 0)
  COLUMNS.forEach((col, idx) => {
    const cellRef = XLSX.utils.encode_cell({ r: 0, c: idx });
    ws[cellRef] = { v: col.header, t: 's' };
  });

  // Column widths
  ws['!cols'] = COLUMNS.map(c => ({ wch: c.width }));

  // Freeze top row
  ws['!freeze'] = { xSplit: 0, ySplit: 1, topLeftCell: 'A2', activePane: 'bottomLeft' };

  // Apply cell styles
  styleHeaderRow(ws, COLUMNS.length);
  styleDataRows(ws, rows.length, COLUMNS.length);

  // Create workbook
  const wb = XLSX.utils.book_new();

  // Metadata sheet
  const metaWs = XLSX.utils.aoa_to_sheet([
    ['Shopify Collections Export'],
    ['Source Store', storeInfo.domain || storeInfo.myshopifyDomain || 'Unknown'],
    ['Exported At', new Date().toISOString()],
    ['Total Collections', collections.length],
    ['Smart (Automated)', collections.filter(c => c.collection_type === 'smart').length],
    ['Custom (Manual)', collections.filter(c => c.collection_type === 'custom').length],
    [],
    ['Schema Version', '2.0'],
    ['Generated By', 'Shopify Collections Excel Exporter'],
  ]);
  metaWs['!cols'] = [{ wch: 20 }, { wch: 40 }];

  XLSX.utils.book_append_sheet(wb, ws, 'Collections');
  XLSX.utils.book_append_sheet(wb, metaWs, 'Export Info');

  // Write to buffer
  const buffer = XLSX.write(wb, { type: 'buffer', bookType: 'xlsx', cellStyles: true });
  return buffer;
}

