export const REQUIRED_HEADERS = [
  'Title',
  'Handle',
  'Type',
  'Description_HTML',
  'Sort_Order',
  'Rules_JSON',
  'Disjunctive',
  'Product_Tags',
  'Product_Handles',
  'Image_URL',
  'Image_Alt'
];

/**
 * Sanitize cell values to prevent formula injection when opening files in Excel.
 * Any string value beginning with =, +, -, or @ is treated as plain text by escaping with a leading quote.
 */
export function sanitizeCellValue(val) {
  if (val === null || val === undefined) return '';
  const str = String(val);
  const trimmed = str.trim();
  if (trimmed.length > 0 && ['=', '+', '-', '@'].includes(trimmed[0])) {
    return `'${trimmed}`;
  }
  return str;
}

/**
 * Parse an uploaded Excel (.xlsx) buffer into an array of collection objects.
 * Enforces:
 * - Verification of required header columns, throwing clear error listing missing columns
 * - Max 1000 data rows
 * - Formula injection prevention for all cells
 * - Row-level error tagging for missing title or malformed rules JSON
 */
export function parseExcelBuffer(buffer) {
  const wb = XLSX.read(buffer, { type: 'buffer', cellFormula: false });

  // Try to find the Collections sheet
  const sheetName = wb.SheetNames.includes('Collections') ? 'Collections' : wb.SheetNames[0];
  const ws = wb.Sheets[sheetName];

  if (!ws) throw new Error('No valid worksheet found in the uploaded Excel file.');

  // 1. Verify header row columns
  const range = XLSX.utils.decode_range(ws['!ref'] || 'A1:A1');
  const foundHeaders = [];
  for (let c = range.s.c; c <= range.e.c; c++) {
    const cellAddress = XLSX.utils.encode_cell({ r: range.s.r, c });
    const cell = ws[cellAddress];
    if (cell && cell.v !== undefined) {
      foundHeaders.push(String(cell.v).trim());
    }
  }

  const normalizeHeader = (h) => String(h || '').toLowerCase().replace(/[\s_-]+/g, '');
  const foundHeaderSet = new Set(foundHeaders.map(normalizeHeader));

  const missingColumns = [];
  for (const req of REQUIRED_HEADERS) {
    if (!foundHeaderSet.has(normalizeHeader(req))) {
      missingColumns.push(req);
    }
  }

  if (missingColumns.length > 0) {
    throw new Error(`Missing required column(s): ${missingColumns.join(', ')}. Please ensure your Excel spreadsheet includes all standard collection columns.`);
  }

  // Convert to array of row objects using the first row as headers
  const rawRows = XLSX.utils.sheet_to_json(ws, { defval: '', raw: false });

  // 2. Enforce maximum row limit of 1000 rows
  if (rawRows.length > 1000) {
    throw new Error(`File contains ${rawRows.length} rows, which exceeds the maximum limit of 1000 rows.`);
  }

  const collections = [];

  for (let rowIndex = 0; rowIndex < rawRows.length; rowIndex++) {
    const row = rawRows[rowIndex];

    // Read and sanitize cell values against formula injection
    const getField = (keys) => {
      for (const k of keys) {
        if (row[k] !== undefined && row[k] !== '') {
          return sanitizeCellValue(row[k]);
        }
      }
      return '';
    };

    const rawTitle = getField(['Title', 'title']);
    const rawHandle = getField(['Handle', 'handle']);
    const rawType = getField(['Type', 'type', 'Collection_Type']);
    const rawDesc = getField(['Description_HTML', 'description_html', 'Description', 'description']);
    const rawSort = getField(['Sort_Order', 'sort_order']);
    const rawTemplate = getField(['Template_Suffix', 'template_suffix']);
    const rawImageUrl = getField(['Image_URL', 'image_url']);
    const rawImageAlt = getField(['Image_Alt', 'image_alt']);
    const rawDisjunctive = getField(['Disjunctive', 'disjunctive']);
    const rawRulesJson = getField(['Rules_JSON', 'rules_json']);
    const rawTags = getField(['Product_Tags', 'product_tags']);
    const rawHandles = getField(['Product_Handles', 'product_handles']);

    // Check if the row is completely blank
    const hasAnyContent = Boolean(
      rawTitle || rawHandle || rawType || rawDesc || rawRulesJson || rawTags || rawHandles || rawImageUrl
    );
    if (!hasAnyContent) continue;

    // Check row-level errors
    let rowError = null;

    if (!rawTitle.trim()) {
      rowError = `Row ${rowIndex + 2}: Missing Title. Collection title is required.`;
    }

    const title = rawTitle.trim();
    const handle = rawHandle.trim()
      || title.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '');

    const collection_type = (rawType || 'smart').toLowerCase() === 'custom' ? 'custom' : 'smart';
    const body_html = rawDesc || '';
    const sort_order = rawSort || 'best-selling';
    const template_suffix = rawTemplate || null;

    const image = rawImageUrl ? { src: rawImageUrl, alt: rawImageAlt || title } : null;
    const disjunctive = String(rawDisjunctive || 'ANY').toUpperCase() !== 'ALL';

    let rules = [];
    if (rawRulesJson) {
      try {
        const jsonToParse = rawRulesJson.startsWith("'") ? rawRulesJson.slice(1) : rawRulesJson;
        rules = JSON.parse(jsonToParse);
        if (!Array.isArray(rules)) {
          rowError = rowError || `Row ${rowIndex + 2}: Rules_JSON must be a valid JSON array.`;
          rules = [];
        }
      } catch {
        rowError = rowError || `Row ${rowIndex + 2}: Invalid JSON syntax in Rules_JSON.`;
        rules = [];
      }
    }

    const product_tags = rawTags
      ? String(rawTags).split(/[;,]/).map(t => t.trim()).filter(Boolean)
      : [];

    // Auto-generate tag rules for smart collections if rules are empty but tags exist
    if (rules.length === 0 && collection_type === 'smart' && product_tags.length > 0) {
      rules = product_tags.map(t => ({ column: 'tag', relation: 'equals', condition: t }));
    }

    const sample_products = rawHandles
      ? String(rawHandles).split(/[;,]/).map(h => ({ handle: h.trim() })).filter(p => p.handle)
      : [];

    collections.push({
      rowIndex: rowIndex + 2,
      title,
      handle,
      collection_type,
      body_html: String(body_html),
      sort_order: String(sort_order),
      template_suffix,
      image_url: rawImageUrl || '',
      image_alt: rawImageAlt || '',
      image,
      disjunctive,
      rules,
      product_tags,
      sample_products,
      status: rowError ? 'error' : 'pending',
      errorReason: rowError || null
    });
  }

  return collections;
}

/**
 * Validate and sanitize a list of parsed collection objects.
 */
export function validateCollections(collections) {
  if (!Array.isArray(collections) || collections.length === 0) {
    throw new Error('No collections found in the import data.');
  }

  return collections.map((c, idx) => {
    const isError = Boolean(c.status === 'error' || c.errorReason || !c.title);
    return {
      rowIndex: c.rowIndex || idx + 2,
      title: c.title ? c.title.trim() : `Untitled Collection ${idx + 1}`,
      handle: c.handle
        ? c.handle.trim()
        : (c.title || `collection-${idx + 1}`).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, ''),
      body_html: c.body_html || '',
      collection_type: c.collection_type === 'custom' ? 'custom' : 'smart',
      sort_order: c.sort_order || 'best-selling',
      template_suffix: c.template_suffix || null,
      image_url: c.image_url || c.image?.src || '',
      image_alt: c.image_alt || c.image?.alt || c.image?.altText || '',
      image: (c.image?.src || c.image_url) ? { src: c.image?.src || c.image_url, alt: c.image?.alt || c.image_alt || c.title } : null,
      disjunctive: c.disjunctive !== undefined ? Boolean(c.disjunctive) : true,
      rules: Array.isArray(c.rules) ? c.rules : [],
      product_tags: Array.isArray(c.product_tags) ? c.product_tags : [],
      sample_products: Array.isArray(c.sample_products) ? c.sample_products : [],
      status: isError ? 'error' : (c.status || 'pending'),
      errorReason: c.errorReason || (c.title ? null : 'Missing Title: Collection title is required.')
    };
  });
}

/**
 * Generate a downloadable Excel report workbook (.xlsx) from import results.
 * Contains one row per collection: Handle, Title, Status, Reason.
 * Ensures formula injection prevention.
 */
export function generateReportWorkbook(reportDetails, storeInfo = {}) {
  const rows = (reportDetails || []).map(item => ({
    Handle: sanitizeCellValue(item.handle || ''),
    Title: sanitizeCellValue(item.title || ''),
    Status: String(item.status || 'unknown').toUpperCase(),
    Reason: sanitizeCellValue(item.reason || item.message || '')
  }));

  const ws = XLSX.utils.json_to_sheet(rows, {
    header: ['Handle', 'Title', 'Status', 'Reason']
  });

  ws['!cols'] = [
    { wch: 30 },
    { wch: 35 },
    { wch: 14 },
    { wch: 60 }
  ];

  // Header styling
  const numCols = 4;
  for (let c = 0; c < numCols; c++) {
    const cellRef = XLSX.utils.encode_cell({ r: 0, c });
    if (ws[cellRef]) {
      ws[cellRef].s = {
        fill: { fgColor: { rgb: '1E293B' } },
        font: { bold: true, color: { rgb: 'FFFFFF' }, sz: 11 },
        alignment: { horizontal: 'center', vertical: 'center' }
      };
    }
  }

  const wb = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(wb, ws, 'Import Report');

  // Metadata sheet
  const metaWs = XLSX.utils.aoa_to_sheet([
    ['Shopify Collection Import Execution Report'],
    ['Store', storeInfo.shop || 'Session Store'],
    ['Generated At', new Date().toISOString()],
    ['Total Collections', reportDetails.length],
    ['Created', reportDetails.filter(r => r.status === 'created' || String(r.status || '').startsWith('created')).length],
    ['Updated', reportDetails.filter(r => r.status === 'updated' || String(r.status || '').startsWith('updated')).length],
    ['Skipped', reportDetails.filter(r => r.status === 'skipped').length],
    ['Failed', reportDetails.filter(r => r.status === 'failed').length]
  ]);
  metaWs['!cols'] = [{ wch: 22 }, { wch: 40 }];
  XLSX.utils.book_append_sheet(wb, metaWs, 'Summary');

  return XLSX.write(wb, { type: 'buffer', bookType: 'xlsx', cellStyles: true });
}
